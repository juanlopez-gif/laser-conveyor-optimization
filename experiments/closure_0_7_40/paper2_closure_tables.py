"""Tables of Paper 2 for the closure review of 0.7.40 (written for 0.7.41). Run from the repository root.

Inputs (all in the repository):
* docs/papers/paper2/data/recheck_0_7_39_geometry.txt   -- observable key, seeds 9000-9059 (retrospective)
* docs/papers/paper2/data/closure_0_7_40/observable_short_cost_ci.txt -- paired intervals of the
  3.33 s vs 10 s cost for those 19 cells (experiments/closure_0_7_40/observable_short_cost_ci.py)
* docs/papers/paper2/data/closure_0_7_40/paper2_prospective_cells.csv -- observable key, fresh seeds
  43700-43759 (experiments/closure_0_7_40/paper2_prospective.py)

Outputs: docs/papers/paper2/tables/bench_observable.tex and bench_fresh.tex.
"""
import ast
import csv
from pathlib import Path

OUT = Path("docs/papers/paper2/tables")
DATA = Path("docs/papers/paper2/data")
ARR = {"poisson": "Poisson", "burst": "bursts"}


def g(x):
    if x is None:
        return "undet."
    if abs(x - 10 / 3) < 1e-9:
        return "3.33"
    return f"{x:g}"


def cost(m, h):
    s = f"{m:+.2f} \\pm {h:.2f}"
    return f"{{\\boldmath${s}$}}" if abs(m) - h > 0 else f"${s}$"


HEAD = [r"\begin{tabular}{@{}cccl cccc@{}}", r"\toprule",
        r"spacing & $v_y$ & $v_x$ & load / arrivals & $G(10\,\mathrm{s})$ & knee & knee (cons.) & cost of 3.33~s \\",
        r"{[cm]} & [cm/s] & [cm/s] & & [s/part] & [s] & [s] & [s/part] \\", r"\midrule"]


def observable():
    ci = {}
    for line in (DATA / "closure_0_7_40/observable_short_cost_ci.txt").read_text().splitlines():
        k, rest = line.rsplit(")", 1)
        m, h = map(float, rest.split())
        ci[ast.literal_eval(k + ")")] = (m, h)
    rows = []
    for line in (DATA / "recheck_0_7_39_geometry.txt").read_text().splitlines():
        if line.startswith("observable-key curve "):
            k = ast.literal_eval(line[len("observable-key curve "):line.index(") {") + 1])
            d = ast.literal_eval(line[line.index(") {") + 2:])
            m, h = ci[k]
            assert abs(m - d["short_cost"]) < 1e-9
            dd, vy, vx, load, arr = k
            rows.append(f"{dd} & {vy} & {vx} & {load} / {ARR[arr]} & ${d['gain']:+.2f}$ & {g(d['point'][0])} & "
                        f"{g(d['conservative'][0])} & {cost(m, h)} \\\\")
    assert len(rows) == 19
    return rows


def fresh():
    rows = []
    with open(DATA / "closure_0_7_40/paper2_prospective_cells.csv", newline="") as f:
        for r in csv.DictReader(f):
            if r["selected"] != "True":
                continue
            rows.append(f"{r['spacing_cm']} & {r['vy_cm_s']} & {r['vx_cm_s']} & {r['load']} / {ARR[r['arrivals']]} & "
                        f"${float(r['full_gain']):+.2f}$ & {g(float(r['point_first']))} & "
                        f"{g(float(r['conservative_first']))} & {cost(float(r['short_cost']), float(r['short_half95']))} \\\\")
    assert len(rows) == 14
    return rows


def write(name, rows, src):
    text = "\n".join([f"% generated by experiments/closure_0_7_40/paper2_closure_tables.py from {src}"]
                     + HEAD + rows + [r"\bottomrule", r"\end{tabular}"]) + "\n"
    (OUT / name).write_text(text, encoding="utf-8")


if __name__ == "__main__":
    write("bench_observable.tex", observable(),
          "data/recheck_0_7_39_geometry.txt and data/closure_0_7_40/observable_short_cost_ci.txt")
    write("bench_fresh.tex", fresh(), "data/closure_0_7_40/paper2_prospective_cells.csv")
    print("written")
