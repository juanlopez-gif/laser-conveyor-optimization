"""PPO baseline over the token policy (docs/methods/rl2_ppo.md).

The question it answers: what does learning from the search teacher (expert
iteration, ``rl2.expert_iteration``) add over learning directly from the reward,
with the **same** representation (``rl2.features``), the same network
(``rl2.model.DispatchNet``, size S), the same action mask, the same simulator
(``fastsim``) and the same cell distribution (``sample_config``)?

* **Decision process.** A decision is a state of the simulator with >= 2 candidate
  parts; decisions with a single candidate are taken without the network and are not
  part of the batches (as ``NetPolicy``). The action is a candidate part; the masked
  categorical policy is ``softmax`` of the pointer logits (non-candidates and padding
  get -inf in ``DispatchNet.forward``).
* **Reward.** Between two consecutive network decisions, minus the increase of the
  penalized objective ``C(t) = WIP integral + lambda_N N_B + lambda_T T_B`` read from
  ``FastSim.cost_so_far()``; the last reward runs to the end of the drained episode.
  gamma = 1, so the return from a decision is minus the cost-to-go of expert
  iteration (``play_episode`` there), and the value head keeps its meaning: the
  normalized cost-to-go, with the same :class:`rl2.model.RunningScale`.
* **Advantages.** GAE(lambda) in cost units: delta_t = c_t + V(s_{t+1}) - V(s_t),
  V(terminal) = 0, A^c_t = sum_l lambda^l delta_{t+l}; the reward advantage is
  -A^c_t, normalized per batch (mean 0, std 1). Value targets are the GAE returns
  A^c_t + V(s_t), normalized by the running scale, which is updated with the
  Monte-Carlo cost-to-go of every new batch (as expert iteration does).
* **Update.** Clipped surrogate, entropy bonus and value MSE; AdamW, gradient
  clipping; several epochs of minibatches over the batch of episodes generated by
  the current policy (sampled actions) on CPU workers, the update on the GPU.
* **Checkpoint selection.** Every ``--val-every`` episodes the greedy policy is scored
  on the validation groups of expert iteration (``validate`` here reuses
  ``val_episode``); the best score is kept as ``models/<tag>.pt``.

Usage::

    python experiments/rl2_ppo.py --tag rl2_ppo_s0 --seed 0 --episodes 40000 --workers 40
"""

from __future__ import annotations

import argparse
import json
import math
import os
import platform
import random
import sys
import time
from concurrent.futures import ProcessPoolExecutor
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np

from rl2.expert_iteration import (ROOT, VAL_GENERAL_SEED_BASE, VAL_GROUPS, VAL_MODES,
                                  VAL_SEED_BASE, _extra, _init_worker, _net, sample_config,
                                  val_episode)

#: training seeds of PPO run ``s`` are ``PPO_SEED_BASE + PPO_SEED_STRIDE * s + e``
#: (200000+, distinct from the expert-iteration seeds 100000+ and far from the
#: reserved seeds 7000-7029 and 9000-9059)
PPO_SEED_BASE = 200_000
PPO_SEED_STRIDE = 100_000


@dataclass(frozen=True)
class PPOConfig:
    clip: float = 0.2
    epochs: int = 4
    minibatch: int = 256
    ent_coef: float = 0.01
    vf_coef: float = 0.5
    lr: float = 3e-4
    weight_decay: float = 1e-4
    max_grad_norm: float = 1.0
    gae_lambda: float = 0.95
    gamma: float = 1.0


# ---------------------------------------------------------------- acting
def penalized_cost(sim) -> float:
    """Penalized objective accumulated so far: WIP integral + lambda_N N_B +
    lambda_T T_B (``FastSim.cost_so_far``)."""
    w, nb, tb = sim.cost_so_far()
    cfg = sim.cfg
    return w + cfg.blocking_penalty_per_event * nb + cfg.blocking_penalty_per_second * tb


def masked_log_probs(logits):
    """log softmax with 0 (not -inf) on the masked entries, so sums are finite."""
    import torch
    logp = torch.log_softmax(logits, -1)
    return torch.where(torch.isfinite(logp), logp, torch.zeros_like(logp))


def entropy(logits):
    """Entropy of the masked categorical, (B,)."""
    import torch
    logp = masked_log_probs(logits)
    return -(torch.exp(logp) * logp).sum(-1)


def sample_action(net, obs, gen):
    """One decision: (index into ``obs.part_ids``, log-prob, normalized value)."""
    import torch
    from rl2.model import collate
    with torch.inference_mode():
        logits, value = net(collate([obs]))
        prob = torch.softmax(logits[0], -1)
        i = int(torch.multinomial(prob, 1, generator=gen))
        return i, float(torch.log(prob[i])), float(value[0])


def play_episode(job: dict) -> dict:
    """One training episode with the sampled policy of the network at ``job["net"]``.

    Returns the decisions with >= 2 candidates: tokens, action index, log-prob and
    normalized value at acting time, and the penalized cost at each decision and at
    the end (the rewards are differences of these)."""
    from fastsim import FastSim
    from rl2.features import encode
    import torch

    seed = job["seed"]
    cfg, kind = sample_config(seed, **job.get("mix", {}), extra=_extra(job))
    net = _net(job["net"])
    gen = torch.Generator().manual_seed(random.Random(f"rl2ppo/{seed}").getrandbits(62))
    sim = FastSim(cfg)
    obs_l, act_l, logp_l, val_l, cost_l = [], [], [], [], []
    t0 = time.perf_counter()
    while sim.run_until_decision():
        cands = sim.candidates()
        if len(cands) == 1:
            sim.apply(cands[0])
            continue
        obs = encode(sim, cands)
        i, lp, v = sample_action(net, obs, gen)
        obs_l.append(obs)
        act_l.append(i)
        logp_l.append(lp)
        val_l.append(v)
        cost_l.append(penalized_cost(sim))
        sim.apply(obs.part_ids[i])
    s = sim.summary()
    return {"obs": obs_l, "act": act_l, "logp": logp_l, "val": val_l, "cost_at": cost_l,
            "final_cost": penalized_cost(sim), "kind": kind, "seed": seed,
            "cost": s["penalized_flow_time"], "decisions": sim.n_decisions,
            "secs": time.perf_counter() - t0}


# ------------------------------------------------------------- advantages
def gae_costs(cost_at, final_cost, values, lam: float, gamma: float = 1.0):
    """GAE in cost units for one episode.

    ``cost_at[t]`` is the penalized objective at decision t, ``final_cost`` at the
    end, ``values[t]`` the predicted cost-to-go (raw units). Returns
    ``(adv, ret, mc)``: the cost advantages A^c_t, the GAE cost returns
    A^c_t + V_t (value targets) and the Monte-Carlo cost-to-go ``final - cost_at``."""
    c = np.asarray(list(cost_at) + [final_cost], np.float64)
    inc = c[1:] - c[:-1]                      # cost of the transition t -> t+1
    v = np.asarray(list(values) + [0.0], np.float64)
    T = len(inc)
    adv = np.zeros(T)
    last = 0.0
    for t in range(T - 1, -1, -1):
        delta = inc[t] + gamma * v[t + 1] - v[t]
        last = delta + gamma * lam * last
        adv[t] = last
    return adv, adv + v[:-1], c[-1] - c[:-1]


def prepare_batch(episodes: list[dict], scale, lam: float, gamma: float = 1.0) -> dict:
    """Turn generated episodes into PPO samples.

    ``scale`` is the running scale the acting network was trained with: it
    denormalizes the predicted values for the GAE, is then updated with the
    Monte-Carlo cost-to-go of these episodes, and normalizes the value targets.
    Returns ``{"obs", "act", "logp", "adv", "vt", "mc"}`` (lists / arrays), with the
    reward advantages normalized per batch."""
    obs, act, logp, adv_c, ret_c, mc = [], [], [], [], [], []
    for e in episodes:
        if not e["obs"]:
            continue
        vals = [scale.denormalize(v) for v in e["val"]]
        a, r, g = gae_costs(e["cost_at"], e["final_cost"], vals, lam, gamma)
        obs += e["obs"]
        act += e["act"]
        logp += e["logp"]
        adv_c.append(a)
        ret_c.append(r)
        mc.append(g)
    adv_c, ret_c, mc = (np.concatenate(x) if x else np.zeros(0) for x in (adv_c, ret_c, mc))
    scale.update(mc)
    adv = -adv_c                                  # reward = minus cost
    adv = (adv - adv.mean()) / max(float(adv.std()), 1e-8) if len(adv) > 1 else adv
    vt = np.asarray([scale.normalize(x) for x in ret_c], np.float64)
    return {"obs": obs, "act": np.asarray(act, np.int64), "logp": np.asarray(logp, np.float64),
            "adv": adv, "vt": vt, "mc": mc}


# ---------------------------------------------------------------- update
def ppo_loss(logits, value, act, logp_old, adv, vt, cfg: PPOConfig):
    """Clipped surrogate + value MSE - entropy on one minibatch. Returns
    ``(loss, stats)``; every tensor is (B,) or (B, P)."""
    import torch
    logp_all = masked_log_probs(logits)
    logp = logp_all.gather(1, act.unsqueeze(1)).squeeze(1)
    ratio = torch.exp(logp - logp_old)
    s1 = ratio * adv
    s2 = torch.clamp(ratio, 1 - cfg.clip, 1 + cfg.clip) * adv
    l_pi = -torch.min(s1, s2).mean()
    l_v = torch.nn.functional.mse_loss(value, vt)
    ent = -(torch.exp(logp_all) * logp_all).sum(-1).mean()
    loss = l_pi + cfg.vf_coef * l_v - cfg.ent_coef * ent
    with torch.no_grad():
        kl = ((ratio - 1) - torch.log(ratio)).mean()          # k3 estimator
        clipfrac = ((ratio - 1).abs() > cfg.clip).float().mean()
    stats = {"policy": l_pi.item(), "value": l_v.item(), "entropy": ent.item(),
             "kl": kl.item(), "clipfrac": clipfrac.item()}
    return loss, stats


def ppo_update(net, batch: dict, cfg: PPOConfig, seed: int, threads: int = 8,
               device: str = "cpu", opt=None) -> dict:
    """``cfg.epochs`` epochs of minibatch updates of ``net`` on ``batch`` (from
    :func:`prepare_batch`). The optimizer persists across updates when given. The
    network comes back on the CPU in eval mode."""
    import torch
    from rl2.model import collate, resolve_device
    dev = resolve_device(device)
    torch.set_num_threads(threads)
    torch.manual_seed(seed)
    net.to(dev)
    if opt is None:
        opt = torch.optim.AdamW(net.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    rng = np.random.default_rng(seed)
    n = len(batch["obs"])
    if n == 0:                                   # a batch of single-candidate episodes
        net.cpu().eval()
        return {"epochs": [], "device": str(dev), "samples": 0}
    act = torch.from_numpy(batch["act"])
    logp_old = torch.from_numpy(batch["logp"].astype(np.float32))
    adv = torch.from_numpy(batch["adv"].astype(np.float32))
    vt = torch.from_numpy(batch["vt"].astype(np.float32))
    hist = []
    net.train()
    for ep in range(cfg.epochs):
        order = rng.permutation(n)
        tot = {"policy": 0.0, "value": 0.0, "entropy": 0.0, "kl": 0.0, "clipfrac": 0.0, "n": 0}
        for s in range(0, n, cfg.minibatch):
            idx = order[s:s + cfg.minibatch]
            b = collate([batch["obs"][i] for i in idx]).to(dev)
            ti = torch.from_numpy(idx)
            logits, value = net(b)
            loss, st = ppo_loss(logits, value, act[ti].to(dev), logp_old[ti].to(dev),
                                adv[ti].to(dev), vt[ti].to(dev), cfg)
            opt.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(), cfg.max_grad_norm)
            opt.step()
            m = len(idx)
            for k in st:
                tot[k] += st[k] * m
            tot["n"] += m
        hist.append({k: tot[k] / tot["n"] for k in tot if k != "n"})
    net.cpu().eval()
    return {"epochs": hist, "device": str(dev), "samples": n}


# ------------------------------------------------------------- validation
def val_jobs(n: int, who: str, net_path, val_mode: str, horizon=None) -> list[dict]:
    seeds = {g: VAL_GENERAL_SEED_BASE if g == "general" else VAL_SEED_BASE for g in VAL_GROUPS}
    return [{"load": g, "seed": seeds[g] + i, "who": who, "net": net_path, "k": 0,
             "w_pen": 0.0, "horizon": horizon, "la": (0.0, 0), "mode": val_mode}
            for g in VAL_GROUPS for i in range(n * (2 if g == "general" else 1))]


def run_val(ex, n: int, who: str, net_path, val_mode: str, horizon=None) -> dict:
    """Episode costs of ``who`` (``net`` at ``net_path``, or a rule) on the
    validation realizations: ``{(group, seed): cost}`` and the CPU seconds."""
    res = list(ex.map(val_episode, val_jobs(n, who, net_path, val_mode, horizon), chunksize=1))
    return {"costs": {(r["load"], r["seed"]): r["cost"] for r in res},
            "cpu_s": float(sum(r["secs"] for r in res))}


def paired(costs: dict, ref: dict) -> dict:
    """Per group: mean paired ratio - 1 vs ``ref`` with its 95 % half-width, the
    number of wins; and the score (mean of the group means)."""
    out = {}
    for g in VAL_GROUPS:
        rs = [c / ref[k] - 1 for k, c in costs.items() if k[0] == g]
        out[g] = {"delta": float(np.mean(rs)),
                  "ci": 1.96 * float(np.std(rs, ddof=1)) / math.sqrt(len(rs)),
                  "n": len(rs), "wins": int(sum(x < 0 for x in rs))}
    out["score"] = float(np.mean([out[g]["delta"] for g in VAL_GROUPS]))
    return out


def fmt(v: dict) -> str:
    return ", ".join(f"{g} {100 * v[g]['delta']:+.2f} +-{100 * v[g]['ci']:.2f} %"
                     for g in VAL_GROUPS) + f" | score {100 * v['score']:+.2f} %"


def _cost_rows(costs: dict) -> list:
    return [[g, s, c] for (g, s), c in sorted(costs.items())]


# ------------------------------------------------------------------- main
def _rel(path) -> str | None:
    if path is None:
        return None
    try:
        return Path(path).resolve().relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def main(argv=None) -> int:
    import torch
    from rl2.model import SIZES, DispatchNet, RunningScale, load, load_scale, resolve_device, save

    d = PPOConfig()
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--tag", default="rl2_ppo_s0")
    ap.add_argument("--seed", type=int, default=0, help="PPO seed: training seeds, "
                    "network init, action sampling and minibatch order")
    ap.add_argument("--size", default="S", choices=sorted(SIZES))
    ap.add_argument("--episodes", type=int, default=40_000, help="training budget")
    ap.add_argument("--batch-episodes", type=int, default=1000, help="episodes per update")
    ap.add_argument("--val-every", type=int, default=4000,
                    help="episodes between checkpoint validations")
    ap.add_argument("--val", type=int, default=50, help="validation seeds per group")
    ap.add_argument("--val-mode", default="design", choices=list(VAL_MODES))
    ap.add_argument("--clip", type=float, default=d.clip)
    ap.add_argument("--epochs", type=int, default=d.epochs)
    ap.add_argument("--minibatch", type=int, default=d.minibatch)
    ap.add_argument("--ent-coef", type=float, default=d.ent_coef)
    ap.add_argument("--vf-coef", type=float, default=d.vf_coef)
    ap.add_argument("--lr", type=float, default=d.lr)
    ap.add_argument("--weight-decay", type=float, default=d.weight_decay)
    ap.add_argument("--max-grad-norm", type=float, default=d.max_grad_norm)
    ap.add_argument("--gae-lambda", type=float, default=d.gae_lambda)
    ap.add_argument("--init", default=None, help="start from this model (fine-tuning)")
    ap.add_argument("--workers", type=int, default=40)
    ap.add_argument("--threads", type=int, default=8, help="torch CPU threads (collate)")
    ap.add_argument("--device", default="auto")
    ap.add_argument("--horizon", type=float, default=None,
                    help="override the arrival horizon [s] (quick runs/tests)")
    args = ap.parse_args(argv)
    cfg = PPOConfig(args.clip, args.epochs, args.minibatch, args.ent_coef, args.vf_coef,
                    args.lr, args.weight_decay, args.max_grad_norm, args.gae_lambda, 1.0)

    mdir = ROOT / "models"
    rdir = ROOT / "results" / "experiments" / args.tag
    rdir.mkdir(parents=True, exist_ok=True)
    logp = mdir / f"{args.tag}_training.json"
    dev = resolve_device(args.device)
    torch.manual_seed(args.seed)
    if args.init:
        net = load(args.init)
        scale = load_scale(args.init) or RunningScale()
    else:
        net = DispatchNet(SIZES[args.size]).eval()
        scale = RunningScale()
    log = {"tag": args.tag, "args": vars(args), "ppo": asdict(cfg),
           "python": platform.python_version(), "torch": torch.__version__,
           "started": time.strftime("%Y-%m-%d %H:%M:%S"),
           "machine": {"host": platform.node(), "cpus": os.cpu_count(),
                       "workers": args.workers, "device": str(dev),
                       "cuda": torch.cuda.get_device_name(0) if dev.type == "cuda" else None},
           "seed_base": PPO_SEED_BASE + PPO_SEED_STRIDE * args.seed,
           "updates": [], "validations": []}
    print(f"{args.tag}: device {dev}, workers {args.workers}, seeds from {log['seed_base']}",
          flush=True)

    def save_log():
        logp.write_text(json.dumps(log, indent=2))

    def act_path(u: int) -> str:
        return str(rdir / f"act_u{u}.pt")

    opt = torch.optim.AdamW(net.parameters(), lr=cfg.lr, weight_decay=cfg.weight_decay)
    n_updates = math.ceil(args.episodes / args.batch_episodes)
    seed_next = log["seed_base"]
    best_score, best = math.inf, None
    t_run = time.perf_counter()
    with ProcessPoolExecutor(args.workers, initializer=_init_worker) as ex:
        t0 = time.perf_counter()
        ref = run_val(ex, args.val, "nearest_job", None, args.val_mode, args.horizon)
        log["reference"] = {"who": "nearest_job", "cpu_s": ref["cpu_s"],
                            "wall_s": time.perf_counter() - t0}
        (rdir / "val_costs_nearest_job.json").write_text(json.dumps(_cost_rows(ref["costs"])))

        def validate(u: int, path: str, candidate: bool) -> dict:
            t0 = time.perf_counter()
            r = run_val(ex, args.val, "net", path, args.val_mode, args.horizon)
            v = paired(r["costs"], ref["costs"])
            (rdir / f"val_costs_u{u}.json").write_text(json.dumps(_cost_rows(r["costs"])))
            entry = {"update": u, "episodes": u * args.batch_episodes, "model": _rel(path),
                     "val": v, "val_s": time.perf_counter() - t0, "val_cpu_s": r["cpu_s"],
                     "candidate": candidate}
            return entry

        save(net, act_path(0), {"update": 0, "scale": [scale.n, scale.mean, scale.m2]})
        v0 = validate(0, act_path(0), False)
        v0["accepted"] = False
        log["validations"].append(v0)
        print(f"  initial: {fmt(v0['val'])}", flush=True)
        save_log()

        for u in range(1, n_updates + 1):
            n_ep = min(args.batch_episodes, args.episodes - (u - 1) * args.batch_episodes)
            jobs = [{"seed": seed_next + e, "net": act_path(u - 1), "horizon": args.horizon}
                    for e in range(n_ep)]
            seed_next += n_ep
            t0 = time.perf_counter()
            eps = list(ex.map(play_episode, jobs, chunksize=4))
            gen_s = time.perf_counter() - t0
            batch = prepare_batch(eps, scale, cfg.gae_lambda, cfg.gamma)
            t0 = time.perf_counter()
            hist = ppo_update(net, batch, cfg, seed=args.seed * 100_000 + u,
                              threads=args.threads, device=args.device, opt=opt)
            train_s = time.perf_counter() - t0
            save(net, act_path(u), {"update": u, "scale": [scale.n, scale.mean, scale.m2]})
            if u >= 2:
                Path(act_path(u - 2)).unlink(missing_ok=True)
            last = hist["epochs"][-1] if hist["epochs"] else dict.fromkeys(
                ("policy", "value", "entropy", "kl", "clipfrac"), math.nan)
            entry = {"update": u, "episodes": n_ep,
                     "episodes_total": min(u * args.batch_episodes, args.episodes),
                     "decisions": len(batch["obs"]),
                     "seeds": [jobs[0]["seed"], jobs[-1]["seed"]],
                     "kinds": {k: sum(1 for e in eps if e["kind"] == k)
                               for k in sorted({e["kind"] for e in eps})},
                     # a bursty cell may have no arrival in the horizon: no parts, no
                     # decisions, an infinite per-part cost; it counts in the budget
                     "cost_mean": float(np.mean([e["cost"] for e in eps
                                                 if math.isfinite(e["cost"])])),
                     "empty_episodes": int(sum(1 for e in eps if not e["obs"])),
                     "mc_cost_to_go_mean": float(batch["mc"].mean()),
                     "all_decisions": int(sum(e["decisions"] for e in eps)),
                     "gen_s": gen_s, "gen_cpu_s": float(sum(e["secs"] for e in eps)),
                     "train_s": train_s, "train": hist,
                     "scale": [scale.n, scale.mean, scale.std]}
            log["updates"].append(entry)
            print(f"update {u}/{n_updates}: {n_ep} ep, {entry['decisions']} dec, cost "
                  f"{entry['cost_mean']:.1f}, policy {last['policy']:+.4f} value "
                  f"{last['value']:.4f} ent {last['entropy']:.3f} kl {last['kl']:.4f} "
                  f"clip {last['clipfrac']:.3f} (gen {gen_s:.0f} s, train {train_s:.0f} s)",
                  flush=True)
            done = u * args.batch_episodes
            if done % args.val_every == 0 or u == n_updates:
                ck = str(mdir / f"{args.tag}_it{u}.pt")
                save(net, ck, {"update": u, "scale": [scale.n, scale.mean, scale.m2]})
                v = validate(u, ck, True)
                accepted = v["val"]["score"] < best_score - 1e-9
                v["accepted"] = accepted
                if accepted:
                    best_score, best = v["val"]["score"], v
                    save(net, mdir / f"{args.tag}.pt",
                         {"update": u, "scale": [scale.n, scale.mean, scale.m2]})
                log["validations"].append(v)
                log["best"] = {"model": _rel(mdir / f"{args.tag}.pt"), "score": best_score,
                               "update": best["update"], "checkpoint": best["model"]}
                print(f"  val @{done}: {fmt(v['val'])} "
                      f"{'ACCEPTED' if accepted else 'rejected'} ({v['val_s']:.0f} s)",
                      flush=True)
            save_log()
    log["finished"] = time.strftime("%Y-%m-%d %H:%M:%S")
    log["wall_s"] = time.perf_counter() - t_run
    save_log()
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT / "src"))
    raise SystemExit(main())
